const ACTIVE: string[] = ['published', 'matched', 'accepted', 'inProgress', 'loadingInProgress', 'inTransit', 'delivered']

export function computeStats(): AdminStats {
  const sum = (txs: Transaction[], pick: (t: Transaction) => number) =>
    txs.reduce((acc, t) => acc + pick(t), 0)
  const released = mockTransactions.filter((t) => t.status === 'released')
  const held = mockTransactions.filter((t) => t.status === 'held')
  return {
    totalOrders: mockOrders.length,
    activeOrders: mockOrders.filter((o) => ACTIVE.includes(o.status)).length,
    completedOrders: mockOrders.filter((o) => o.status === 'completed').length,
    registeredUsers: mockUsers.length,
    creditedToExecutors: String(
      sum(released, (t) => Number(t.amount) - Number(t.platformCommission)),
    ),
    serviceFeesCharged: String(sum(released, (t) => Number(t.platformCommission))),
    heldInEscrow: String(sum(held, (t) => Number(t.amount))),
  }
}
